export function resolveHomeGuideRole(
  role: 'student' | 'admin' | 'superadmin',
  isEnrolled: boolean,
): HomeGuideRole {
  if (role === 'student') return isEnrolled ? 'student_enrolled' : 'student';
  if (role === 'superadmin') return 'superadmin';
  return 'admin';
}

